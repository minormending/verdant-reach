def build() -> None:
    for name, im in T.items():
        gbc.save(im, f"tiles/{name}.png")
    review()


def review() -> None:
    cells = []
    for name, im in T.items():
        patch = Image.new("RGBA", (48 + 4 + 16, 48))
        for y in range(3):
            for x in range(3):
                patch.paste(im, (x * 16, y * 16))
        patch.paste(im, (52, 0))
        cells.append((f"{name} q{gbc.quad_colour_counts(im)}", patch))
    gbc.grid_sheet(cells, 6, 4).save(gbc.REVIEW / "tiles.png")


if __name__ == "__main__":
    build()
    if "-v" in sys.argv:
        for n, im in T.items():
            print(n, len(gbc.colours(im)), gbc.quad_colour_counts(im))
