"""Hand-authored 16x16 GBC tiles -> public/assets/tiles/<key>.png (+ __2 frames).

Every tile is an ASCII pixel map with its own small key into the master
colour list (gbc.C). Ground tiles tile seamlessly; obstacles sit on the
ground colour they're normally placed on. Run, then look at
tools/art/review/tiles.png (each tile is shown alone and as a 3x3 patch).
"""

from __future__ import annotations

import sys

from PIL import Image

import gbc
from gbc import img_from_rows

T: dict[str, Image.Image] = {}


def tile(name: str, rows: list[str], key: dict) -> Image.Image:
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    im = img_from_rows(rows, key)
    T[name] = im
    return im


def quad(motif: list[str], offset=0) -> list[str]:
    """Tile an 8x8 motif 2x2; the lower row is shifted by `offset` px."""
    top = [r + r for r in motif]
    bot = [(r + r)[offset:] + (r + r)[:offset] for r in motif]
    return top + bot


def overlay(base: list[str], patch: list[str], x: int, y: int, clear=" ") -> list[str]:
    rows = [list(r) for r in base]
    for j, pr in enumerate(patch):
        for i, ch in enumerate(pr):
            if ch != clear:
                rows[y + j][x + i] = ch
    return ["".join(r) for r in rows]


