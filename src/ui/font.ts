/** Characters normalised to a glyph we have. */
const ALIASES: Record<string, string> = {
  "’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", " ": " ",
  "É": "é", "▸": "▶", "►": "▶", "▽": "▼", "⋯": "…", "x́": "×",
};

/** Glyph bitmaps: char -> 8 rows of 8 bits (bit 7 = leftmost column). */
export const GLYPHS: Map<string, number[]> = (() => {
  const map = new Map<string, number[]>();
  for (const block of BLOCKS) {
    const chars = Array.from(block.chars);
    if (block.rows.length !== GLYPH_H) throw new Error(`font block ${block.chars}: needs 8 rows`);
    chars.forEach((ch, i) => {
      const bits: number[] = [];
      for (const row of block.rows) {
        const cell = row.split(" ")[i];
        if (!cell || cell.length !== GLYPH_W) throw new Error(`font glyph ${ch}: bad row "${row}"`);
        let b = 0;
        for (let c = 0; c < GLYPH_W; c++) if (cell[c] === "#") b |= 0x80 >> c;
        bits.push(b);
      }
      map.set(ch, bits);
    });
  }
  return map;
})();

const warned = new Set<string>();
/** Resolve a character to a glyph key (aliases, then '?' fallback). */
export function glyphKey(ch: string): string {
  if (GLYPHS.has(ch)) return ch;
  const alias = ALIASES[ch];
  if (alias && GLYPHS.has(alias)) return alias;
  if (!warned.has(ch)) {
    warned.add(ch);
    console.warn(`[font] no glyph for ${JSON.stringify(ch)}; drawing "?"`);
  }
  return "?";
}

/** Width in pixels (monospace: 8px per character). */
export function measureText(text: string): number {
  let longest = 0;
  for (const line of text.split("\n")) longest = Math.max(longest, Array.from(line).length);
  return longest * GLYPH_W;
}

/**
 * Word-wrap to `maxCols` characters per line. "\n" forces a break; words
 * longer than a line are split. Blank lines from "\n\n" are preserved as "".
 */
export function wrapText(text: string, maxCols: number): string[] {
  const out: string[] = [];
  for (const para of text.split("\n")) {
    const words = para.split(/ +/).filter((w) => w.length > 0);
    if (words.length === 0) { out.push(""); continue; }
    let line = "";
    for (let word of words) {
      while (Array.from(word).length > maxCols) {
        if (line) { out.push(line); line = ""; }
        const chars = Array.from(word);
        out.push(chars.slice(0, maxCols).join(""));
        word = chars.slice(maxCols).join("");
      }
      const candidate = line ? `${line} ${word}` : word;
      if (Array.from(candidate).length > maxCols) {
        out.push(line);
        line = word;
      } else {
        line = candidate;
      }
    }
    out.push(line);
  }
  return out;
}

/**
 * Split text into pages for the text box. Paragraph breaks ("\n\n" or "\f")
 * start a fresh box; everything else scrolls line by line, as in Crystal.
 */
export function paragraphs(text: string, maxCols: number): string[][] {
  return text
    .replace(/\r/g, "")
    .split(/\f|\n{2,}/)
    .map((p) => wrapText(p.trim(), maxCols))
    .filter((lines) => lines.some((l) => l.length > 0));
}

/** Replace player/rival placeholders: {PLAYER}, <PLAYER>, [PLAYER] (and RIVAL). */
export function formatText(text: string, names: { player: string; rival: string }): string {
  return text
    .replace(/[{<[]PLAYER[}>\]]/g, names.player || "YOU")
    .replace(/[{<[]RIVAL[}>\]]/g, names.rival || "BRAM");
}

