const ATLAS_COLS = 16;
const atlasIndex = new Map<string, number>();
for (const ch of GLYPHS.keys()) atlasIndex.set(ch, atlasIndex.size);
const atlases = new Map<string, HTMLCanvasElement>();

/** Atlas canvas for one colour, plus the source rect of each glyph. */
export function glyphAtlas(color: string): HTMLCanvasElement {
  let canvas = atlases.get(color);
  if (canvas) return canvas;
  canvas = document.createElement("canvas");
  const rows = Math.ceil(atlasIndex.size / ATLAS_COLS);
  canvas.width = ATLAS_COLS * GLYPH_W;
  canvas.height = rows * GLYPH_H;
  const g = canvas.getContext("2d")!;
  g.fillStyle = color;
  for (const [ch, idx] of atlasIndex) {
    const bits = GLYPHS.get(ch)!;
    const ox = (idx % ATLAS_COLS) * GLYPH_W;
    const oy = Math.floor(idx / ATLAS_COLS) * GLYPH_H;
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) if (bits[y] & (0x80 >> x)) g.fillRect(ox + x, oy + y, 1, 1);
    }
  }
  atlases.set(color, canvas);
  return canvas;
}

export function glyphRect(ch: string): { sx: number; sy: number } {
  const idx = atlasIndex.get(glyphKey(ch)) ?? 0;
  return { sx: (idx % ATLAS_COLS) * GLYPH_W, sy: Math.floor(idx / ATLAS_COLS) * GLYPH_H };
}

/** Draw text with the bitmap font. "\n" starts a new 8px line. Scale >= 1. */
export function drawBitmapText(
  g: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1,
): void {
  const atlas = glyphAtlas(color);
  let cx = Math.round(x);
  let cy = Math.round(y);
  for (const ch of Array.from(text)) {
    if (ch === "\n") { cx = Math.round(x); cy += GLYPH_H * scale; continue; }
    if (ch !== " ") {
      const { sx, sy } = glyphRect(ch);
      g.drawImage(atlas, sx, sy, GLYPH_W, GLYPH_H, cx, cy, GLYPH_W * scale, GLYPH_H * scale);
    }
    cx += GLYPH_W * scale;
  }
}
